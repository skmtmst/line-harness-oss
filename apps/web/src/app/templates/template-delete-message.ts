/**
 * テンプレートを削除する前に読み合わせる本文。
 *
 * もとはブラウザの `confirm()` で「このテンプレートは N 箇所で使用されています。
 * 削除すると参照がクリアされます。続行しますか？」と出していた。何が止まり・
 * 何が残り・戻せるのかが読めないうえ、画像比較にも写らなかった。
 *
 * 使用箇所の数で言うことが変わるので、画面から切り出して単体で確かめられる
 * ようにしてある。画面ごと組み立てると、0箇所のときの言い回しを誰も見ない。
 */
export function templateDeleteDescription(usageCount: number): string {
  if (usageCount > 0) {
    return (
      `このテンプレートは${usageCount}箇所で使われています。` +
      '削除すると、その箇所からの参照が外れ、本文が空のまま動きます。' +
      'すでに送ったメッセージは残ります。この操作は取り消せません。'
    )
  }
  return (
    'どこからも使われていないので、他の画面の動きは止まりません。' +
    'すでに送ったメッセージは残ります。この操作は取り消せません。'
  )
}
