-- シナリオの並行購読を、いまの動きのまま使えるようにする。
--
-- 103 で allow_concurrent を足したが、既定が 0（並行を許さない）だった。
-- いまは1人が複数のシナリオに同時に入れるので、そのまま有効にすると
-- 「昨日まで届いていた配信が届かない」という形で表に出る。
--
-- 既にある行を 1 に寄せて、これまでと同じ動きを保つ。
-- 並行を止めたい人は、画面から個別に 0 にする。
--
-- 新しく作るシナリオも 1 で作る（アプリ側が必ず値を渡す）。列の既定 0 は
-- 使われない。列の既定を変えるには表の作り直しが要り、追加のみポリシーで
-- 禁じているため、この形にした。
UPDATE scenarios SET allow_concurrent = 1 WHERE allow_concurrent = 0;
