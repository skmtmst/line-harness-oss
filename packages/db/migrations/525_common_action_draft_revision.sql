--
-- これまで同じ下書きの版IDは編集を重ねても変わらず、別担当が先に保存した
-- 後の古い内容の保存を検知できなかった(R473: 60分が5分に戻る)。
-- 公開も下書きIDの照合だけだったため、読取後に保存が入った古い内容を
-- 公開してしまっていた(R477: 保存済み60分が5分で公開される)。
--
-- 保存ごとに進む改訂番号を照合し、古い読み取りからの保存・公開は409で止める。
-- 競合時は両者の差分を確認し直してから保存・公開し直す。
--
-- 付け足すだけ(ADD COLUMN)。既存の行はすべて 1 のままで、
-- 1 のままの行は従来どおり最初の改訂として扱う(今の動きを変えない)。
ALTER TABLE common_action_versions ADD COLUMN draft_revision INTEGER NOT NULL DEFAULT 1;
