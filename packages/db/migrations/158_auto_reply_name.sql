-- 自動応答に、管理用の名前を持たせる。
--
-- いまは keyword を名前の代わりに一覧へ出している。**一律で応答するルール（157）には
-- キーワードが無い**ので、「すべてのメッセージ」としか出ない。一律のルールを
-- 2つ作った時点で、一覧から見分けられなくなる。
--
-- Lステップも「自動応答名」を必須の別項目として持っている（キーワードとは別）。
--
-- 空のままでも今までどおり動く。名前が無ければ、これまでどおり keyword を出す。
ALTER TABLE auto_replies ADD COLUMN name TEXT;

-- キーワードが複数あるとき、どれか1つで当てるか、全部そろって当てるか。
--
-- いまは「どれか1つ」だけ。Lステップは「どれか一つにマッチするとき応答／
-- すべてにマッチする時のみ応答」を選ばせている。
--
-- 「すべてにマッチ」は、絞り込みに使う。「予約」と「キャンセル」の両方が
-- 入った文にだけ返す、という形。どちらか片方だけの問い合わせには返さない。
--
-- 既にあるルールは 'any'（どれか1つ）。動きは変わらない。
ALTER TABLE auto_replies ADD COLUMN keyword_match_mode TEXT NOT NULL DEFAULT 'any';
