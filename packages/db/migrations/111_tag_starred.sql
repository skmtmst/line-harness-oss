-- タグを友だち一覧に出すかどうかの印。
--
-- 設計（V2 3-1 / 3-1-1）はタグ一覧に「表示」列があり、★の付いたタグだけが
-- 友だち一覧の「★つきタグ」列に出る。タグを何十個も作る運用で、一覧の狭い
-- 列に全部並べると、どれも読めなくなるため。
--
-- friend_fields には同じ意図の is_starred が 099 で入っている（★を付けた
-- 項目だけが友だち一覧の「★つき友だち情報」列に出る）。タグ側にだけ無く、
-- 画面から印を付けられなかった。同じ名前・同じ既定値でそろえる。
--
-- 既定は 0（出さない）。既にあるタグの見え方は変わらない。付けたものだけが
-- 増える方向なので、当てても一覧が急に埋まることはない。
ALTER TABLE tags ADD COLUMN is_starred INTEGER NOT NULL DEFAULT 0;
