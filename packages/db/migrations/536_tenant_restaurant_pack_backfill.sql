-- 統括単位の飲食店機能ゲートを実効化するにあたり、既存統括が
-- 突然アクセスを失わないようにするバックフィル。
--
-- `tenants.feature_packs`（#568）はこれまで表示専用ラベルだったため、
-- 既存の全統括が既定値 '[]'（パック無し）のまま残っている。今回、
-- restaurant-test 系のゲートを実効化する変更と同時に適用すると、
-- feature_packs が空の既存統括（既定の統括を含む）は即座に
-- 飲食店機能へアクセスできなくなる。
--
-- 既に `restaurant` パックを持つ統括はそのままにし、まだ持たない
-- 既存統括だけへ付与する。以後、運営コンソールで新規に作る統括は
-- 既定どおりパック無し（明示的にオンにするまで使えない）。
UPDATE tenants
SET feature_packs = '["restaurant"]'
WHERE feature_packs = '[]';
