-- 初回返信の時刻。
--
-- 設計は受信箱とダッシュボードの両方に「平均の初回返信 18分」を出す。
-- いまは受信してから最初に返すまでの時間を記録していないので出せない。
--
-- messages_log から都度計算することもできるが、友だち1人につき
-- 全メッセージを走査することになり、一覧を開くたびに重い。
-- chats に1列持たせて、送信時に「まだ入っていなければ入れる」だけにする。
--
-- 過去ぶんは埋まらない。入れた日から先の返信だけが平均に入る。
-- 埋めようとすると messages_log を全部読むことになり、そこまでの
-- 価値は無いと判断した。
ALTER TABLE chats ADD COLUMN first_replied_at TEXT;

-- 直近の受信時刻。初回返信の時間は「この時刻からの差」で出す。
-- last_message_at は送受信どちらでも動くので、受信だけの時刻が別に要る。
ALTER TABLE chats ADD COLUMN last_incoming_at TEXT;
