-- キーワードを問わず、届いたメッセージすべてに応答する形。
--
-- 時間帯の設定（曜日・時間帯・祝日）は入れたが、**キーワードに当たらないと
-- 返らない**ままだった。「営業時間外は必ずこれを返す」が作れない。時間帯を
-- 入れた意味が半分しか出ていない状態。
--
-- Lステップも「キーワードで応答／一律で応答」をタブで分けている。
--
-- 既存の列（keyword が空なら一律、など）で表さないのは、「キーワードが空」が
-- 「書き忘れ」とも読めるため。意図が伝わらない。
--
-- 既にあるルールは 0（キーワードで応答）。動きは変わらない。
ALTER TABLE auto_replies ADD COLUMN respond_to_all INTEGER NOT NULL DEFAULT 0;
